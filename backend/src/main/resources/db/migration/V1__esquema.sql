-- ============================================================
--  LADO DE COMANDOS (escritura): modelo normalizado + outbox
-- ============================================================
create schema if not exists comando;

create table comando.pedido (
    id             varchar(36)              primary key,
    cliente        varchar(120)             not null,
    total          numeric(12,2)            not null,
    estado         varchar(20)              not null,
    creado_en      timestamp with time zone not null,
    actualizado_en timestamp with time zone not null
);

create table comando.pedido_item (
    id              bigint generated by default as identity primary key,
    pedido_id       varchar(36)    not null references comando.pedido (id),
    producto        varchar(120)   not null,
    cantidad        int            not null,
    precio_unitario numeric(12,2)  not null
);

-- Bandeja de salida (patrón Outbox): el evento se guarda en la MISMA transacción que el pedido
create table comando.outbox_evento (
    id         bigint generated by default as identity primary key,
    event_id   varchar(36)              not null unique,
    clave      varchar(36)              not null,
    tipo       varchar(30)              not null,
    payload    text                     not null,
    creado_en  timestamp with time zone not null,
    publicado  boolean                  not null default false
);
create index idx_outbox_pendiente on comando.outbox_evento (publicado, id);

-- El lado de CONSULTAS ya no vive en PostgreSQL: usa MongoDB (colecciones pedido_vista y evento_aplicado).
